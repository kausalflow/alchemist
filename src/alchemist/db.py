class Database:
    dialect: str
    fts: bool

    def execute(self, sql: str, params=()):
        raise NotImplementedError

    def commit(self) -> None: ...

    @contextmanager
    def transaction(self):
        raise NotImplementedError
        yield

    def close(self) -> None: ...


# ---------------------------------------------------------------- SQLite

class SqliteDatabase(Database):
    dialect = "sqlite"

    def __init__(self, path: str):
        # Used by one request or one run step at a time, but those may hop threads (FastAPI runs sync code in a
        # pool). Run steps in other processes write here too, so wait for a lock rather than fail on "locked".
        self.conn = sqlite3.connect(path, check_same_thread=False, timeout=30)
        self.conn.row_factory = sqlite3.Row
        self._migrate()

    def execute(self, sql: str, params=()):
        return self.conn.execute(sql, params)

    def commit(self) -> None:
        self.conn.commit()

    @contextmanager
    def transaction(self):
        try:
            yield self
        except BaseException:
            self.conn.rollback()
            raise
        self.conn.commit()

    def close(self) -> None:
        self.conn.close()

    def _migrate(self) -> None:
        self.conn.execute("create table if not exists schema_migrations (version integer primary key, name text,"
                          " applied_at text)")
        done = {r[0] for r in self.conn.execute("select version from schema_migrations")}
        self.fts = 3 in done
        for version, name, sql, _ in MIGRATIONS:
            if version in done:
                continue
            try:
                self.conn.executescript(sql)
                if version == 3:
                    self.fts = True
            except sqlite3.OperationalError:
                if version != 3:
                    raise
            self.conn.execute("insert or ignore into schema_migrations values (?, ?, datetime('now'))", (version, name))
            self.conn.commit()
        if 3 in done:  # a database migrated by a build with FTS5, opened by one without it
            try:
                self.conn.execute("select 1 from card_search limit 0")
            except sqlite3.OperationalError:
                self.fts = False


# ---------------------------------------------------------------- PostgreSQL

_pools: dict[str, object] = {}
_migrated: set[str] = set()
_lock = threading.Lock()
MIGRATION_LOCK = 0x616C6368  # "alch": pg_advisory_xact_lock key while migrating


def _conninfo(url: str) -> str:
    from psycopg.conninfo import conninfo_to_dict, make_conninfo

    params = conninfo_to_dict(url)
    if "password" not in params and os.environ.get("ALC_DB_PASSWORD"):
        params["password"] = os.environ["ALC_DB_PASSWORD"]
    params.setdefault("application_name", "alchemist")
    return make_conninfo(**params)


def _pool(url: str):
    with _lock:
        pool = _pools.get(url)
        if pool is None:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool

            # Every API request and run step borrows a connection for its own work and gives it back on close().
            pool = ConnectionPool(_conninfo(url), min_size=1, max_size=int(os.environ.get("ALC_DB_POOL_SIZE", "10")),
                                  kwargs={"autocommit": True, "row_factory": dict_row},
                                  check=ConnectionPool.check_connection, open=True, name="alchemist")
            if not _pools:
                atexit.register(close_pools)  # else the pool's threads hold up interpreter exit
            _pools[url] = pool
        return pool


def close_pools() -> None:
    """Close every PostgreSQL pool (tests, and processes that are about to exit)."""
    with _lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()
        _migrated.clear()


def _pg_sql(sql: str) -> str:
    # The app writes `?` placeholders (SQLite style); psycopg wants `%s`, and a literal % must be doubled.
    return sql.replace("%", "%%").replace("?", "%s")


class PostgresDatabase(Database):
    dialect = "postgres"
    fts = True
    conn = None

    def __init__(self, url: str):
        self.url = url
        self.pool = _pool(url)
        self.conn = None
        conn = self.pool.getconn()
        try:
            if url not in _migrated:
                migrate_postgres(conn)
                _migrated.add(url)
        except BaseException:
            self.pool.putconn(conn)
            raise
        self.conn = conn

    def execute(self, sql: str, params=()):
        return self.conn.execute(_pg_sql(sql), tuple(params))

    def commit(self) -> None:
        pass  # autocommit: each statement outside transaction() commits on its own

    @contextmanager
    def transaction(self):
        with self.conn.transaction():
            yield self

    def close(self) -> None:
        if self.conn is not None:
            conn, self.conn = self.conn, None
            self.pool.putconn(conn)

    def __del__(self):
        # Safety net for a Catalog dropped without close(): give its connection back rather than drain the pool.
        try:
            self.close()
        except Exception:
            pass


def migrate_postgres(conn) -> list[int]:
    """Apply pending migrations; safe to call from many tasks at once. Returns the versions applied."""
    applied = []
    with conn.transaction():
        conn.execute("select pg_advisory_xact_lock(%s)", (MIGRATION_LOCK,))
        conn.execute("create table if not exists schema_migrations (version integer primary key, name text,"
                     " applied_at timestamptz not null default now())")
        done = {r["version"] for r in conn.execute("select version from schema_migrations")}
        for version, name, _, sql in MIGRATIONS:
            if version in done:
                continue
            conn.execute(sql)
            conn.execute("insert into schema_migrations(version, name) values (%s, %s)", (version, name))
            applied.append(version)
    return applied


def connect(target: str) -> Database:
    """Open the app database: a PostgreSQL URL, or a SQLite file path."""
    if is_postgres(target):
        return PostgresDatabase(target)
    return SqliteDatabase(target)
