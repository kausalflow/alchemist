"""Deployment settings for one environment (dev, staging, prod), read from infra/config/<env>.yaml.

Everything account-specific lives here: region, VPC, identity provider, buckets, Bedrock profiles, domain names.
Nothing in the constructs hard-codes an account value.
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ExistingVpc(_Model):
    """An existing VPC from the landing zone. Subnet lists are aligned with availability_zones."""

    vpc_id: str
    availability_zones: list[str]
    public_subnet_ids: list[str]
    public_route_table_ids: list[str] = []
    app_subnet_ids: list[str]
    app_route_table_ids: list[str]
    # Subnets for the API service when it needs HTTPS egress (network.api_egress); default: the app subnets,
    # in which case the landing zone must provide that egress.
    api_subnet_ids: list[str] = []
    api_route_table_ids: list[str] = []
    sandbox_subnet_ids: list[str]
    sandbox_route_table_ids: list[str]
    data_subnet_ids: list[str]
    vpc_cidr: str


class Network(_Model):
    # Create a new VPC (default) or deploy into an existing one.
    cidr: str = "10.40.0.0/20"
    # Zones for a new VPC; default <region>a and <region>b.
    availability_zones: list[str] = []
    # The API verifies the ALB's signed OIDC header with the key from public-keys.auth.elb.<region>.amazonaws.com,
    # which is on the internet. True adds an "api" subnet tier routed through one NAT gateway, used only by the API
    # service; orchestrator, sandbox, indexers and the database stay without any route out.
    api_egress: bool = True
    existing: ExistingVpc | None = None


class LakeBucket(_Model):
    name: str
    # Customer-managed key of the bucket, if any. Its key policy must allow the run and indexer roles to decrypt.
    kms_key_arn: str | None = None


class Lake(_Model):
    buckets: list[LakeBucket]
    # How a plant's data is found in a lake bucket. The credential broker reads grants that the API writes
    # with these prefixes; the template is passed to the app as ALC_PLANT_PREFIX_TEMPLATE.
    plant_prefix_template: str = "s3://{bucket}/plant={plant}/"


class Storage(_Model):
    # Bucket names; generated by CloudFormation when left empty.
    workspace_bucket_name: str | None = None
    knowledge_bucket_name: str | None = None
    # Versioning on Alchemist's own workspace bucket is an open question; Object Lock needs it.
    workspace_versioning: bool = False
    object_lock_governance_days: int | None = None
    work_expiry_days: int = 90
    # The app's catalog and run index is SQLite today (Postgres is planned). True puts it on an encrypted EFS file
    # system mounted at /data in the API and worker tasks, so they share one database (ALC_DB=/data/alchemist.db).
    shared_sqlite: bool = True
    # Access rules for the "yaml" access provider (users, plant groups, workspaces, identity claim mapping); key in
    # the workspace bucket, uploaded by an admin.
    access_file_key: str = "_config/access.yaml"
    # Keep buckets, keys and the database when the stack is deleted.
    retain_data: bool = True


class Oidc(_Model):
    issuer: str
    authorization_endpoint: str
    token_endpoint: str
    user_info_endpoint: str
    client_id: str
    # Name of an existing Secrets Manager secret holding the client secret as a plain string.
    client_secret_name: str
    scope: str = "openid email profile groups"
    group_claim: str = "groups"
    session_timeout_hours: int = 8


class Domain(_Model):
    # Name users open, e.g. alchemist.example.com. Served by CloudFront.
    name: str
    # ACM certificate for `name`, in us-east-1 (CloudFront requirement).
    cloudfront_certificate_arn: str
    # Name CloudFront uses to reach the ALB, e.g. alchemist-origin.example.com, and an ACM certificate in the
    # stack's region covering both this name and `name` (CloudFront forwards the viewer's Host header, so it
    # checks the ALB certificate against `name`).
    api_origin_name: str
    alb_certificate_arn: str
    # Optional Route 53 zone to create the two records in; otherwise create them in your DNS.
    hosted_zone_id: str | None = None
    hosted_zone_name: str | None = None
    # Managed prefix list com.amazonaws.global.cloudfront.origin-facing in the region, to restrict the ALB to
    # CloudFront at the network level. Without it, the ALB only accepts requests carrying the origin secret.
    cloudfront_prefix_list_id: str | None = None


class Bedrock(_Model):
    # Model specs passed to the app as ALC_LEAD_MODEL / ALC_SUB_MODEL, normally application inference profile ARNs.
    lead_model: str
    sub_model: str
    embedding_model: str = "amazon.titan-embed-text-v2:0"
    # Everything the roles and the VPC endpoint may invoke: inference profile ARNs and the foundation-model
    # ARNs behind them (Bedrock checks both).
    allowed_model_arns: list[str]
    # Account-wide setting for the region: turn it off if other teams share the account.
    invocation_logging: bool = True
    invocation_log_retention_days: int = 365
    guardrail: bool = True


class Image(_Model):
    # Build the image from the repository Dockerfile (default), or use a pushed image pinned by digest.
    ecr_repository_arn: str | None = None
    digest: str | None = None

    @model_validator(mode="after")
    def _both_or_none(self):
        if bool(self.ecr_repository_arn) != bool(self.digest):
            raise ValueError("image.ecr_repository_arn and image.digest go together")
        return self


class Modules(_Model):
    """Optional parts of the stack. The core (network, storage, database, Bedrock, services, run workflow) is always on."""

    edge: bool = True            # CloudFront and the SPA bucket deployment; off if another front door is used
    observability: bool = True   # alarms, CloudTrail, break-glass role
    indexers: bool = True        # nightly catalog index and knowledge ingestion schedules


class Plugins(_Model):
    """App plugins (see docs/guides/plugins.md) and infrastructure plugins (see docs/guides/deploy-aws.md)."""

    # pip requirement specs installed into the image next to alchemist, e.g. "acme-alchemist==1.2.0" or a wheel
    # path relative to the repository root. Pin versions: the image digest is what a manifest records.
    packages: list[str] = []
    # ALC_PLUGINS: entry-point names to load. Keep it explicit in production; "*" loads every installed plugin.
    enabled: list[str] = []
    # ALC_PLUGIN_MODULES: importable modules to load without an entry point.
    modules: list[str] = []
    # ALC_ACCESS_PROVIDER: the registered access provider for users, plant groups and workspaces. "alb-oidc" takes
    # users only from the verified identity-provider claims; plants, workspaces and group-name patterns still come
    # from ALC_ACCESS (storage.access_file_key).
    access_provider: str = "alb-oidc"
    # Extra environment for every app container, e.g. settings a plugin reads.
    env: dict[str, str] = {}
    # Infrastructure plugins: importable modules with `register(ctx: InfraContext)`, in addition to installed
    # packages that declare the entry-point group `alchemist.infra`.
    infra: list[str] = []
    discover_infra_entry_points: bool = True


class TaskSize(_Model):
    cpu: int
    memory_mib: int
    ephemeral_gib: int = 20  # Fargate default; 21-200 adds storage


class Sizes(_Model):
    api: TaskSize = TaskSize(cpu=1024, memory_mib=2048)
    # Several writers on SQLite over NFS lock unreliably, so keep one API task while storage.shared_sqlite is on.
    api_count: int = 1
    orchestrator: TaskSize = TaskSize(cpu=1024, memory_mib=2048)
    sandbox: TaskSize = TaskSize(cpu=4096, memory_mib=16384, ephemeral_gib=100)
    indexer: TaskSize = TaskSize(cpu=2048, memory_mib=8192, ephemeral_gib=50)
    sealer: TaskSize = TaskSize(cpu=512, memory_mib=1024)


class Database(_Model):
    min_acu: float = 0.5
    max_acu: float = 8
    backup_days: int = 14
    deletion_protection: bool = True


class Commands(_Model):
    """Container commands (arguments to the `alchemist` entry point). Kept here so app renames don't need code."""

    api: list[str] = ["api", "--host", "0.0.0.0", "--port", "8080"]
    api_port: int = 8080
    api_health_path: str = "/healthz"
    plan: list[str] = ["worker", "plan", "--run-id"]
    analyse: list[str] = ["worker", "analyse", "--run-id"]
    replay: list[str] = ["worker", "replay", "--run-id"]
    report: list[str] = ["worker", "report", "--run-id"]
    seal: list[str] = ["worker", "seal", "--run-id"]
    sandbox: list[str] = ["sandbox", "serve", "--port", "8888"]
    sandbox_port: int = 8888
    catalog_index: list[str] = ["catalog", "index"]
    knowledge_ingest: list[str] = ["knowledge", "ingest"]
    migrate: list[str] = ["db", "migrate"]


class Workflow(_Model):
    # in_process: the analyse task runs the kernel itself, assumes the run role (ALC_RUN_ROLE_ARN) for data access,
    #   and builds the report and seals the run; this is what the app does today.
    # separate: the target design; the kernel runs in a sandbox task that gets data credentials only from the
    #   broker Lambda and has no route to Bedrock; Report and Seal are their own steps.
    sandbox_mode: Literal["in_process", "separate"] = "in_process"
    approval_timeout_days: int = 14
    analysis_timeout_hours: int = 6
    # Nightly catalog re-index and knowledge ingestion (UTC cron, EventBridge syntax).
    index_schedule: str = "cron(0 2 * * ? *)"


class Operations(_Model):
    alarm_email: str | None = None
    log_retention_days: int = 90
    create_trail: bool = True
    # Principals (e.g. an SSO admin role) allowed to assume the alarmed break-glass role. Empty: no role.
    break_glass_principal_arns: list[str] = []


class EnvConfig(_Model):
    env_name: str = Field(pattern=r"^[a-z][a-z0-9-]{1,15}$")
    account: str = Field(pattern=r"^\d{12}$")
    region: str
    network: Network = Network()
    lake: Lake
    storage: Storage = Storage()
    oidc: Oidc
    domain: Domain
    bedrock: Bedrock
    image: Image = Image()
    modules: Modules = Modules()
    plugins: Plugins = Plugins()
    sizes: Sizes = Sizes()
    database: Database = Database()
    commands: Commands = Commands()
    workflow: Workflow = Workflow()
    operations: Operations = Operations()
    # Built SPA (index.html and assets) to upload, relative to the repository root. Skipped if absent.
    web_dist_path: str = "web/dist"
    tags: dict[str, str] = {}

    @model_validator(mode="after")
    def _object_lock_needs_versioning(self):
        if self.storage.object_lock_governance_days and not self.storage.workspace_versioning:
            raise ValueError("storage.object_lock_governance_days needs storage.workspace_versioning: true")
        return self

    @model_validator(mode="after")
    def _packages_need_a_build(self):
        if self.plugins.packages and self.image.ecr_repository_arn:
            raise ValueError("plugins.packages are installed at image build; with a pinned image, bake them into it")
        if self.plugins.env.keys() & {"ALC_PLUGINS", "ALC_PLUGIN_MODULES", "ALC_ACCESS_PROVIDER"}:
            raise ValueError("set plugin selection with plugins.enabled, plugins.modules and plugins.access_provider")
        return self

    @model_validator(mode="after")
    def _one_api_on_shared_sqlite(self):
        if self.storage.shared_sqlite and self.sizes.api_count > 1:
            raise ValueError("sizes.api_count > 1 needs Postgres; SQLite on EFS supports one API task")
        return self

    @property
    def prefix(self) -> str:
        return f"alchemist-{self.env_name}"


Stage = Literal["dev", "staging", "prod"]

CONFIG_DIR = Path(__file__).resolve().parent.parent / "config"


def load_config(env: str, path: str | Path | None = None) -> EnvConfig:
    p = Path(path) if path else CONFIG_DIR / f"{env}.yaml"
    return EnvConfig.model_validate(yaml.safe_load(p.read_text()))
